import matplotlib.pyplot as plt

months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
          'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

users = [1200, 1350, 1500, 1450, 1700, 1850,
         1800, 2100, 2300, 2200, 2500, 2800]

plt.plot(months, users, marker='o')

plt.title('Spotify Daily Active Users')
plt.xlabel('Months')
plt.ylabel('Number of Users')

plt.annotate('Highest Users',
             xy=('Dec', 2800),
             xytext=('Sep', 3000),
             arrowprops=dict(arrowstyle='->'))

plt.grid(True)
plt.show()

