import matplotlib.pyplot as plt

apps = ["Instagram", "YouTube", "WhatsApp", "Zomato", "Spotify"]
hours = [3, 2, 2, 1, 2]

plt.pie(hours, labels=apps, autopct="%1.1f%%")

plt.title("Daily App Usage")
plt.show()

categories = ["Food Delivery", "Shopping", "Entertainment", "UPI Payments"]
spending = [2000, 5000, 1500, 3000]

explode = [0, 0.1, 0, 0]

plt.pie(spending, labels=categories, autopct="%1.1f%%",
        explode=explode)

plt.title("Monthly Online Spending")
plt.show()

categories = ["Food Delivery", "Shopping", "Entertainment", "UPI Payments"]
spending = [2000, 5000, 1500, 3000]

fig, ax = plt.subplots()

ax.pie(spending, labels=categories, autopct="%1.1f%%")

circle = plt.Circle((0, 0), 0.6, color="white")
ax.add_artist(circle)

ax.set_title("Monthly Online Spending Donut Chart")
plt.show()

