import matplotlib.pyplot as plt

restaurants = ['Dominos', 'Pizza Hut', 'McDonalds',
               'Burger King', 'Subway']

orders = [120, 90, 150, 80, 100]

plt.bar(restaurants, orders)

plt.title('Zomato Restaurant Orders')
plt.xlabel('Restaurants')
plt.ylabel('Number of Orders')

plt.xticks(rotation=20)

plt.savefig('zomato_orders.png', dpi=150)
plt.show()

days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']
steps = [4000, 5500, 6000, 7500, 8000, 10000, 9000]

plt.plot(days, steps, marker='o')

plt.title('My Daily Step Count')
plt.xlabel('Days')
plt.ylabel('Number of Steps')

plt.savefig('daily_steps.svg')
plt.show()

apps = ['Instagram', 'YouTube', 'WhatsApp', 'Spotify']
hours = [3, 4, 2, 1]

plt.pie(hours, labels=apps, autopct='%1.1f%%')

plt.title('My Daily App Usage')

plt.savefig('app_usage.pdf')
plt.show()

