import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

steps = [4000, 6000, 5000, 8000, 7500, 10000, 9000]
water = [2, 2.5, 2, 3, 2.5, 3.5, 3]

plt.figure(figsize=(8, 6))

# First subplot: Steps
plt.subplot(2, 1, 1)
plt.plot(days, steps, marker="o")
plt.title("Daily Step Count")
plt.xlabel("Days")
plt.ylabel("Number of Steps")

# Second subplot: Water intake
plt.subplot(2, 1, 2)
plt.plot(days, water, marker="o", color="green")
plt.title("Daily Water Intake")
plt.xlabel("Days")
plt.ylabel("Water (Litres)")

plt.tight_layout()
plt.show()

quarters = ["Q1", "Q2", "Q3", "Q4"]
posts = [20, 35, 28, 45]

fig, ax = plt.subplots(2, 2, figsize=(10, 8))

# Line chart
ax[0, 0].plot(quarters, posts, marker="o")
ax[0, 0].set_title("Line Chart")

# Bar chart
ax[0, 1].bar(quarters, posts)
ax[0, 1].set_title("Bar Chart")

# Scatter plot
ax[1, 0].scatter(quarters, posts)
ax[1, 0].set_title("Scatter Plot")

# Pie chart
ax[1, 1].pie(posts, labels=quarters, autopct="%1.1f%%")
ax[1, 1].set_title("Pie Chart")

plt.tight_layout()
plt.show()

