import numpy as np
orders = [3, 5, 2, 8, 6, 4, 7, 9, 3, 10, 5, 6]
amount = [600, 1200, 400, 2000, 1500, 900,
          1800, 2500, 700, 2800, 1300, 1600]

# Create scatter plot
plt.scatter(orders, amount, label="Friends")

# Calculate slope and intercept
slope, intercept = np.polyfit(orders, amount, 1)

# Draw trend line
plt.plot(orders, np.polyval([slope, intercept], orders),
         color="red", label="Trend Line")

plt.xlabel("Number of Zomato Orders")
plt.ylabel("Amount Spent (Rs)")
plt.title("Zomato Orders with Trend Line")
plt.legend()

plt.show()

print("Slope:", slope)
print("Intercept:", intercept)

youtube = [2, 4, 3, 5, 6, 2, 7, 8, 4, 6, 9, 5, 3, 7, 10]
spotify = [3, 5, 4, 6, 7, 3, 8, 9, 5, 7, 10, 6, 4, 8, 11]

# Create scatter plot
plt.scatter(youtube, spotify)

# Calculate regression line
slope, intercept = np.polyfit(youtube, spotify, 1)

# Generate trend line
x_line = np.linspace(min(youtube), max(youtube), 100)
y_line = slope * x_line + intercept

plt.plot(x_line, y_line, color="red")

# Print equation on the graph
equation = f"y = {slope:.2f}x + {intercept:.2f}"
plt.text(2, 10, equation, fontsize=12)

plt.xlabel("YouTube Watch Hours")
plt.ylabel("Spotify Listening Hours")
plt.title("YouTube vs Spotify Usage")

plt.show()

print("Regression Equation:", equation)

