import matplotlib.pyplot as plt

days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]

zomato = [10, 12, 8, 15, 18, 20, 16]
swiggy = [8, 10, 9, 12, 14, 17, 13]

plt.bar(days, zomato, label="Zomato", color="orange")
plt.bar(days, swiggy, bottom=zomato, label="Swiggy", color="green")

plt.title("Daily Food Orders")
plt.xlabel("Days")
plt.ylabel("Number of Orders")
plt.legend()

plt.show()

