import pandas as pd

data = {
    'product': ['Laptop', 'Shirt', 'Rice', 'Mobile', 'Jeans',
                'Headphones', 'Wheat', 'Dress', 'Tablet', 'Sugar',
                'Laptop', 'Shirt', 'Rice', 'Mobile', 'Jeans',
                'Headphones', 'Wheat', 'Dress', 'Tablet', 'Sugar'],
    'category': ['Electronics', 'Clothing', 'Groceries', 'Electronics',
                 'Clothing', 'Electronics', 'Groceries', 'Clothing',
                 'Electronics', 'Groceries'] * 2,
    'date': ['2025-01-10', '2025-01-15', '2025-02-05', '2025-02-12',
             '2025-03-08', '2025-03-20', '2025-04-02', '2025-04-18',
             '2025-05-11', '2025-05-22', '2025-06-04', '2025-06-16',
             '2025-07-09', '2025-07-21', '2025-08-03', '2025-08-14',
             '2025-09-06', '2025-10-12', '2025-11-17', '2025-12-20'],
    'sales_amount': [50000, 1200, 800, 25000, 1800,
                     3000, 1000, 2200, 15000, 600,
                     55000, 1500, 900, 28000, 2000,
                     3500, 1100, 2500, 17000, 700]
}

df = pd.DataFrame(data)

df['date'] = pd.to_datetime(df['date'])

df.to_csv('sales_data.csv', index=False)

print(df.head())

import matplotlib.pyplot as plt

category_sales = df.groupby('category')['sales_amount'].sum()

plt.bar(category_sales.index, category_sales.values)

plt.title('Total Sales by Product Category')
plt.xlabel('Category')
plt.ylabel('Total Sales (Rs)')

plt.show()

df['date'] = pd.to_datetime(df['date'])

monthly_sales = df.groupby(df['date'].dt.month)['sales_amount'].sum()

plt.plot(monthly_sales.index, monthly_sales.values, marker='o')

plt.title('Monthly Sales Trends - 2025')
plt.xlabel('Month')
plt.ylabel('Total Sales (Rs)')

plt.xticks(range(1, 13))
plt.grid(True)

plt.show()

plt.hist(df['sales_amount'], bins=10, edgecolor='black')

plt.title('Distribution of Order Amounts')
plt.xlabel('Sales Amount (Rs)')
plt.ylabel('Number of Orders')

plt.show()

category_sales = df.groupby('category')['sales_amount'].sum()

plt.bar(category_sales.index, category_sales.values)

plt.title('Category Sales KPI')
plt.xlabel('Product Category')
plt.ylabel('Total Sales (Rs)')

for i, value in enumerate(category_sales.values):
    plt.text(i, value, str(value), ha='center', va='bottom')

plt.savefig('category_sales_kpi.png', dpi=150, bbox_inches='tight')

plt.show()